const NAV_ITEMS = [
  { key: "devices", label: "Devices", icon: Icons.Devices },
  { key: "send", label: "Send SMS", icon: Icons.Send },
  { key: "templates", label: "Templates", icon: Icons.Templates },
  { key: "logs", label: "SMS Logs", icon: Icons.Logs },
  { key: "apikeys", label: "API Keys", icon: Icons.ApiKeys },
];

export default function UserSidebar({ active, onSelect, user, onLogout, onAdmin, open, onClose }) {
  return (
    <>
      {open && <div onClick={onClose} className="sidebar-overlay" />}

      <aside className={`sidebar ${open ? "sidebar-open" : ""}`}>
        {/* Gradient Header */}
        <div className="sidebar-header">
          <div className="sidebar-brand">Casuya SMS</div>
          <div className="sidebar-sub">SMS Gateway</div>
        </div>

        <nav className="sidebar-nav">
          {NAV_ITEMS.map((item) => {
            const isActive = active === item.key;
            const Icon = item.icon;
            return (
              <button
                key={item.key}
                onClick={() => { onSelect(item.key); onClose(); }}
                className={`sidebar-item ${isActive ? "sidebar-item-active" : ""}`}
              >
                <span className="sidebar-icon"><Icon /></span>
                <span>{item.label}</span>
              </button>
            );
          })}

          {user?.role === "admin" && (
            <>
              <div className="sidebar-divider" />
              <button
                onClick={() => { onAdmin(); onClose(); }}
                className="sidebar-item sidebar-item-admin"
              >
                <span className="sidebar-icon"><Icons.Admin /></span>
                <span>Admin Panel</span>
              </button>
            </>
          )}
        </nav>

        <div className="sidebar-footer">
          <div className="sidebar-user">
            <div className="sidebar-avatar">
              {user?.email?.[0]?.toUpperCase() || "?"}
            </div>
            <div className="sidebar-user-info">
              <div className="sidebar-email">{user?.email}</div>
              {user?.role === "admin" && (
                <div className="sidebar-role">Admin</div>
              )}
            </div>
          </div>
          <button onClick={onLogout} className="sidebar-logout">
            <Icons.Logout /> Sign Out
          </button>
        </div>
      </aside>
    </>
  );
}
