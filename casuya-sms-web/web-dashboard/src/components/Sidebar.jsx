export default function Sidebar({
  active,
  onSelect,
  user,
  open,
  onClose,
  ariaLabel = "Sidebar navigation",
  sidebarId,
  headerSub = "",
  headerClass = "",
  avatarClass = "",
  roleLabel,
  navItems = [],
  extraNav = null,
  footer = null,
}) {
  const navRef = useRef(null);

  useEffect(() => {
    if (open && navRef.current) navRef.current.focus();
  }, [open]);

  return (
    <>
      {open && (
        <div className="sidebar-overlay is-visible" onClick={onClose} aria-hidden="true" />
      )}

      <aside
        id={sidebarId}
        className={`sidebar ${open ? "sidebar-open" : ""}`}
        aria-label={ariaLabel}
      >
        <div className={`sidebar-header ${headerClass}`}>
          <div className="sidebar-brand">Casuya SMS</div>
          <div className="sidebar-sub">{headerSub}</div>
        </div>

        <nav className="sidebar-nav" ref={navRef} tabIndex={-1}>
          {navItems.map((item) => {
            const isActive = active === item.key;
            const Icon = item.icon;
            return (
              <button
                key={item.key}
                onClick={() => { onSelect(item.key); onClose(); }}
                aria-current={isActive ? "page" : undefined}
                className={`sidebar-item ${isActive ? "sidebar-item-active" : ""}`}
              >
                <span className="sidebar-icon"><Icon /></span>
                <span style={{ flex: 1 }}>{item.label}</span>
                {item.count !== undefined && (
                  <span className={`sidebar-badge ${isActive ? "sidebar-badge-active" : ""}`}>
                    {item.count}
                  </span>
                )}
              </button>
            );
          })}
          {extraNav}
        </nav>

        <div className="sidebar-footer">
          <div className="sidebar-user">
            <div className={`sidebar-avatar ${avatarClass}`}>
              {user?.email?.[0]?.toUpperCase() || "?"}
            </div>
            <div className="sidebar-user-info">
              <div className="sidebar-email">{user?.email}</div>
              {roleLabel && <div className="sidebar-role">{roleLabel}</div>}
            </div>
          </div>
          {footer}
        </div>
      </aside>
    </>
  );
}
